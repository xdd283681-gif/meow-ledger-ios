  assert.equal(await page.evaluate(()=>window.__meowPage.data.form.date),'2026-10-28');
  await page.evaluate(()=>window.__meowBack());
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-account="public"]').click();
  assert.match(await page.locator('.hero-amount').innerText(),/0.00/);
  await page.locator('.nav-add').click();
  assert.match(await page.locator('.entry-account').innerText(),/公账/);
  await page.getByRole('textbox',{name:'金额',exact:true}).fill('120.50');
  await page.locator('input[placeholder="为这笔记录加点故事"]').fill('公账采购');
  await page.getByRole('button',{name:'记好啦',exact:true}).click();
  await page.waitForSelector('.sheet',{state:'detached'});
  await page.locator('[data-tab="home"]').click();
  await page.locator('.budget-card').click();
  await page.getByRole('textbox',{name:'月预算',exact:true}).fill('500');
  await page.getByRole('button',{name:'就这样定啦',exact:true}).click();
  await page.waitForSelector('.sheet',{state:'detached'});
  await page.reload();await page.waitForSelector('.hero-amount');
  assert.equal(await page.locator('.account-option.active').innerText(),'公账');
  assert.match(await page.locator('.hero-amount').innerText(),/120.50/);
  assert.match(await page.locator('.budget-meta').innerText(),/500.00/);
  await page.screenshot({path:'release/test-evidence/ios-public-1.0.4.png'});
  await page.locator('[data-tab="mine"]').click();
  await page.getByRole('button',{name:/导出当前账本/}).click();
