  await page.getByRole('button',{name:'记好啦',exact:true}).click();
  await page.waitForSelector('.sheet',{state:'detached'});
  assert.equal(await page.locator('.confirm-card').count(),0);
  assert.equal(await page.evaluate(()=>window.__nativeEvents.some(e=>e.action==='hideKeyboard')),true);
  await page.reload();await page.waitForSelector('.hero-amount');
  assert.match(await page.locator('.hero-amount').innerText(),/66.88/);
  await page.locator('.bill-row').click();
  await page.getByRole('button',{name:'删除这笔记录',exact:true}).click();
  assert.equal(await page.evaluate(()=>window.__meowBack()),true);
  await page.waitForSelector('.confirm-card',{state:'detached'});
  assert.equal(await page.locator('.sheet').count(),1,'Back cancels deletion and preserves form');
  assert.equal(await page.evaluate(()=>window.__meowBack()),true);
  assert.equal(await page.evaluate(()=>localStorage.getItem('meow-ledger-v1')),null,'Native data must use native storage');
  console.log('PASS iOS 存储接口、确认取消、保存后收起键盘、重启持久化');
  await page.locator('[data-tab="mine"]').click();
  await page.getByRole('button',{name:/导出当前账本/}).click();
  const exported=await page.evaluate(()=>window.__nativeEvents.find(e=>e.csv));
  assert.ok(exported.csv.startsWith('\ufeff账本,日期'));assert.ok(exported.csv.includes('iOS独立记账'));
  assert.match(exported.filename,/^meow-ledger-personal-.*\.csv$/);
  assert.equal(await page.locator('#toast.visible').count(),0,'Do not claim export succeeded before iOS saves the file');
  await page.getByRole('button',{name:/数据与隐私/}).click();
  assert.match(await page.locator('.confirm-message').innerText(),/iOS/);
  assert.equal(await page.evaluate(()=>window.__meowBack()),true);
  assert.equal(await page.evaluate(()=>window.__meowBack()),true);
  await page.waitForSelector('.hero-amount');
  assert.equal(await page.evaluate(()=>window.__meowBack()),false);
  console.log('PASS CSV 原生保存请求、隐私说明、返回首页与退出分流');
  await page.locator('.bill-row').click();
  await page.getByRole('textbox',{name:'金额',exact:true}).fill('99');
  await page.evaluate(()=>window.__failSave=true);
  await page.getByRole('button',{name:'保存修改',exact:true}).click();
  assert.equal(await page.locator('.sheet').count(),1);
  assert.equal(await page.evaluate(()=>window.__meowPage.book.transactions[0].amount),6688);
  assert.match(await page.locator('#toast').innerText(),/保存失败/);
  await page.evaluate(()=>{window.__failSave=false;window.__meowBack();});
  await page.locator('.nav-add').click();
  await page.getByRole('textbox',{name:'金额',exact:true}).fill('12');
  await page.locator('input[placeholder="为这笔记录加点故事"]').fill('键盘布局');
